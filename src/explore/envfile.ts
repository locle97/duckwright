import fs from "node:fs";
import path from "node:path";

import { ENV_MAX_BYTES } from "../environment.ts";
import { flat, neutralise } from "../text.ts";
import type { Sitemap } from "./site.ts";

export const GEN_START_PREFIX = "<!-- duckwright:generated:start";
export const GEN_END = "<!-- duckwright:generated:end -->";
export const HAND_HEADING = "## Notes (yours)";

export interface RenderOptions {
  treeDepth: number;
  maxPages: number;
  maxPerSection: number;
  /** Header, base URL and business summary only. */
  businessOnly?: boolean;
}
const FULL: RenderOptions = { treeDepth: 4, maxPages: 120, maxPerSection: 20 };
// Shrink order: tree depth first, then page count, then per-section note counts, then business only.
const SHRINK: RenderOptions[] = [
  ...[4, 3, 2, 1, 0].map((treeDepth) => ({ treeDepth, maxPages: 120, maxPerSection: 20 })),
  ...[60, 30, 10, 0].map((maxPages) => ({ treeDepth: 0, maxPages, maxPerSection: 20 })),
  ...[12, 8, 4, 2].map((maxPerSection) => ({ treeDepth: 0, maxPages: 0, maxPerSection })),
  { treeDepth: 0, maxPages: 0, maxPerSection: 5, businessOnly: true },
];

/** Agent-authored text comes from pages: one line, no block markers, no harness tags that could close a prompt section. */
const safe = (s: string) => neutralise(flat(s)).replaceAll("<!--", "<! --").replaceAll("-->", "-- >");
const BUSINESS_SHOWN = 3;
const bullets = (xs: string[], max: number) => xs.slice(0, max).map((x) => `- ${safe(x)}`);
const section = (title: string, lines: string[]) => (lines.length ? [`## ${title}`, ...lines, ""] : []);

export function renderGenerated(sm: Sitemap, opts: RenderOptions = FULL): string {
  const root = sm.pages.find((p) => p.depth === 0)?.url ?? null;
  const rel = (url: string, status: string) => {
    const u = new URL(url);
    if (url === root) return "/";
    if (status === "external") return safe(u.origin + u.pathname);
    return u.pathname === "/" ? "/" : safe(u.pathname);
  };
  const tree = sm.pages
    .filter((p) => p.depth <= opts.treeDepth)
    .slice(0, opts.maxPages)
    .map((p) => {
      const tags = [p.status !== "ok" ? p.status : "", p.purpose ? safe(p.purpose) : ""].filter(Boolean);
      return `${"  ".repeat(Math.min(p.depth, opts.treeDepth))}- ${rel(p.url, p.status)}${tags.length ? ` (${tags.join("; ")})` : ""}`;
    });
  const flows = sm.flows.slice(0, opts.maxPerSection).map((f) => `- ${safe(f.title)}: ${f.status}${f.notes ? ` (${safe(f.notes)})` : ""}`);
  const lines = [
    `${GEN_START_PREFIX} run=${sm.runs} -->`,
    `# ${safe(sm.host)} (generated by duckwright explore, run ${sm.runs}; may be out of date)`,
    "",
    ...(root ? [`Base URL: ${safe(new URL(root).origin)}/`, ""] : []),
    ...section("Business", bullets(sm.notes.business.slice(-BUSINESS_SHOWN), opts.maxPerSection)),
    ...(opts.businessOnly
      ? []
      : [
          ...section("Roles and accounts", bullets(sm.notes.account, opts.maxPerSection)),
          ...section("Key flows", flows),
          ...section("Quirks", bullets(sm.notes.quirk, opts.maxPerSection)),
          ...section("Off-limits", bullets(sm.notes["off-limits"], opts.maxPerSection)),
          ...section("Sitemap", tree),
        ]),
    GEN_END,
  ];
  return lines.join("\n");
}

const BAD_MARKERS = "generated block markers are duplicated or incomplete; only the last complete block was replaced (or a fresh block appended) and the rest was left alone";
const bytes = (s: string) => Buffer.byteLength(s, "utf8");

function findBlock(text: string): { start: number; end: number; clean: boolean } | null {
  const starts = [...text.matchAll(/<!-- duckwright:generated:start[^>]*-->/g)];
  const ends = [...text.matchAll(/<!-- duckwright:generated:end -->/g)];
  if (starts.length === 0 && ends.length === 0) return null;
  const clean = starts.length === 1 && ends.length === 1 && ends[0].index! > starts[0].index!;
  // The live block is the last start marker that has an end marker after it.
  for (let i = starts.length - 1; i >= 0; i--) {
    const from = starts[i].index! + starts[i][0].length;
    const end = ends.find((e) => e.index! >= from);
    if (end) return { start: starts[i].index!, end: end.index! + GEN_END.length, clean };
  }
  return null;
}

function fit(sm: Sitemap, room: number): { block: string; trimmed: boolean } {
  for (const [i, o] of SHRINK.entries()) {
    const block = renderGenerated(sm, o);
    if (bytes(block) <= room) return { block, trimmed: i > 0 };
  }
  const minimal = `${GEN_START_PREFIX} run=${sm.runs} -->\n${GEN_END}`;
  return { block: bytes(minimal) <= room ? minimal : "", trimmed: true };
}

/** The new file text: only the generated block changes; everything else is kept byte-for-byte. */
export function updateEnvText(existing: string | null, sm: Sitemap): { text: string; warnings: string[] } {
  const warnings: string[] = [];
  if (existing === null) {
    const { block } = fit(sm, ENV_MAX_BYTES - bytes(`\n\n${HAND_HEADING}\n`));
    return { text: `${block}\n\n${HAND_HEADING}\n`, warnings };
  }
  const found = findBlock(existing);
  let before: string;
  let after: string;
  if (found === null) {
    if (/<!-- duckwright:generated:(start|end)/.test(existing)) warnings.push(BAD_MARKERS);
    before = existing.endsWith("\n") || existing === "" ? existing : existing + "\n";
    before += existing === "" ? "" : "\n";
    after = "\n";
  } else {
    if (!found.clean) warnings.push(BAD_MARKERS);
    before = existing.slice(0, found.start);
    after = existing.slice(found.end);
  }
  const { block, trimmed } = fit(sm, ENV_MAX_BYTES - bytes(before) - bytes(after));
  if (trimmed) warnings.push("the environment file is near its size limit; the generated block was shortened");
  if (block === "") {
    warnings.push("no room for a generated block under the size limit; shorten the hand-written part");
    if (found === null) return { text: existing, warnings };
  }
  return { text: before + block + after, warnings };
}

/** Atomic write (temp file, then rename); returns warnings. */
export function writeEnvFile(file: string, sm: Sitemap): string[] {
  let existing: string | null = null;
  try {
    existing = fs.readFileSync(file, "utf8");
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== "ENOENT") throw e;
  }
  const { text, warnings } = updateEnvText(existing, sm);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.tmp-${process.pid}`;
  try {
    fs.writeFileSync(tmp, text);
    fs.renameSync(tmp, file);
  } finally {
    fs.rmSync(tmp, { force: true });
  }
  return warnings;
}
